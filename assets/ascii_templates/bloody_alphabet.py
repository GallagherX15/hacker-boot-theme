def render_bloody_text(text, letter_spacing="  "):
    lines = [""] * 6
    for char in text.upper():
        matrix = BLOODY_ALPHABET.get(char, BLOODY_ALPHABET.get(' '))
        for row in range(6):
            lines[row] += matrix[row] + letter_spacing
    return lines
